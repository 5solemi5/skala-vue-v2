const fwLaunch = (cue) => {
  const rr = fwRng
  fwShells.push({
    x: cue.x + (rr() - 0.5) * 10,
    // 강 위에서 솟는다. 다리 뒤쪽 배에서 쏘아 올린다고 치자
    y: 172,
    vx: cue.vx + (rr() - 0.5) * 6,
    /*
     * 얼마나 높이 올라가느냐.
     *
     * 처음엔 건물 꼭대기 언저리에서 터졌다. 실제 불꽃놀이는 그보다 한참
     * 위에서 터지고, 무엇보다 하늘이 넓게 열려 있어야 터진 공이 다 보인다.
     * 건물에 걸치면 아무리 잘 터져도 반쯤 잘린 그림이다.
     *
     * 올린 높이 = 처음 빠르기 × 심지 시간 − 중력이 되돌린 만큼.
     * 이 둘로 터지는 자리가 y 37~69 에 온다 — 스카이라인 꼭대기(y 88)와
     * 랜드마크(y 74)보다 확실히 위다.
     */
    vy: -(88 + rr() * 12) * cue.hi,
    fuse: (1.5 + rr() * 0.25) / cue.hi,
    age: 0,
    pal: FW_PALETTES[cue.p],
    type: cue.type,
    scale: cue.sc,
  })
}

const fwBurst = (sh) => {
  const rr = fwRng
  /*
   * 하늘 전체의 반짝임.
   *
   * 알갱이를 하늘 곳곳에 흩어 놓고 제자리에서 빠르게 깜빡이게 둔다.
   * 한 점에서 뻗어 나오게 하면 그냥 큰 불꽃 하나가 되는데, 이건
   * 터진 자리와 상관없이 어디를 봐도 반짝이는 그 순간이다.
   *
   * 거의 움직이지 않는다(항력 2.6). 움직이면 흩날리는 것이 되고,
   * 흩날리면 반짝임이 아니라 불티다.
   */
  if (sh.type === 'glitter') {
    for (let i = 0; i < 230; i++) {
      fwSparks.push({
        x: rr() * 820 - 10,
        y: 6 + rr() * 132,
        vx: (rr() - 0.5) * 7,
        vy: (rr() - 0.5) * 5 + 3,
        age: 0,
        life: 1 + rr() * 1.4,
        drag: 2.6,
        ci: rr() < 0.66 ? 0 : 1,
        pal: sh.pal,
        // 아주 빠르게 깜빡인다. 이 빠르기가 '반짝' 을 만든다
        tw: 32 + rr() * 30,
        twp: rr() * 6.283,
      })
    }
    fwFlash = 1.9
    return
  }
  /*
   * 고리.
   *
   * 국화는 빠르기를 제각각으로 줘서 안쪽에도 알갱이가 있는 '공' 이지만,
   * 고리는 모두 같은 빠르기로 나가서 껍데기만 남는다. 한가운데가
   * 비어 있는 그 동그라미가 고리를 고리로 만든다.
   *
   * 그래서 여기서만은 빠르기를 흩지 않는다 — 국화에서 굴렁쇠가 되지
   * 않으려고 흩었던 바로 그것을, 여기서는 일부러 맞춘다.
   */
  if (sh.type === 'ring') {
    const n = Math.round(54 * sh.scale)
    for (let i = 0; i < n; i++) {
      const a = (i / n) * 6.283 + rr() * 0.05
      const sp = 54 * sh.scale * (0.96 + rr() * 0.08)
      fwSparks.push({
        x: sh.x,
        y: sh.y,
        vx: Math.cos(a) * sp + sh.vx * 0.3,
        vy: Math.sin(a) * sp + sh.vy * 0.22,
        age: 0,
        life: 1.5 + rr() * 0.7,
        drag: 1.2,
        ci: rr() < 0.75 ? 0 : 1,
        pal: sh.pal,
        tw: 16 + rr() * 14,
        twp: rr() * 6.283,
      })
    }
    fwFlash = Math.min(1.9, fwFlash + 0.34 * sh.scale)
    return
  }

  /*
   * 야자수.
   *
   * 알갱이를 몇 개만, 대신 굵고 오래. 항력을 거의 걸지 않아 멀리까지
   * 뻗어 나갔다가 중력에 잡혀 아래로 휜다 — 그 휜 몇 갈래가 야자잎이다.
   *
   * 수가 적어야 갈래가 보인다. 많이 넣으면 그냥 큰 국화가 된다.
   */
  if (sh.type === 'palm') {
    const n = Math.round(11 * sh.scale)
    for (let i = 0; i < n; i++) {
      const a = (i / n) * 6.283 + rr() * 0.18
      const sp = (46 + rr() * 12) * sh.scale
      fwSparks.push({
        x: sh.x,
        y: sh.y,
        vx: Math.cos(a) * sp + sh.vx * 0.3,
        vy: Math.sin(a) * sp + sh.vy * 0.22,
        age: 0,
        life: 2.6 + rr() * 0.9,
        drag: 0.34,
        ci: 0,
        pal: sh.pal,
        tw: 9 + rr() * 8,
        twp: rr() * 6.283,
        // 굵게 그린다. 갈래가 굵어야 잎으로 보인다
        fat: true,
      })
    }
    fwFlash = Math.min(1.9, fwFlash + 0.4 * sh.scale)
    return
  }

  const big = sh.type === 'pop' ? 34 : 68
  const n = Math.round(big * sh.scale)
  const willow = sh.type === 'willow'
  for (let i = 0; i < n; i++) {
    /*
     * 방향은 고르게, 빠르기는 제각각.
     *
     * 빠르기까지 고르면 알갱이가 정확한 원 위에 놓여 굴렁쇠가 된다.
     * 안쪽에도 바깥쪽에도 있어야 공으로 보인다.
     */
    const a = (i / n) * 6.283 + rr() * 0.16
    /*
     * 터지는 크기.
     *
     * 작게 잡았더니 하늘에 불티가 조금 튄 정도였다. 알갱이가 멎기까지
     * 가는 거리는 대략 빠르기 나누기 항력이라 이 둘이 터진 공의 반지름을
     * 정한다. 판 너비의 십분의 일은 되어야 하늘에서 터진 것으로 보인다.
     */
    const sp = (willow ? 34 + rr() * 28 : 42 + rr() * 46) * sh.scale
    fwSparks.push({
      x: sh.x,
      y: sh.y,
      vx: Math.cos(a) * sp + sh.vx * 0.3,
      vy: Math.sin(a) * sp + sh.vy * 0.22,
      age: 0,
      life: (willow ? 2.4 : 1.5) + rr() * 1.1,
      // 버들은 오래 매달려 흘러내린다. 항력이 약해서 그렇다
      drag: willow ? 0.5 : 1 + rr() * 0.45,
      ci: rr() < 0.72 ? 0 : 1,
      pal: sh.pal,
      // 꺼질 무렵의 깜빡임. 알갱이마다 박자가 다르다
      tw: 14 + rr() * 16,
      twp: rr() * 6.283,
    })
  }
  fwFlash = Math.min(1.9, fwFlash + 0.5 * sh.scale)
}

const stepFireworks = (t, dt, mirrorOn) => {
  /*
   * 악보를 따라간다.
   * 한 바퀴가 끝나면 처음으로 돌아가 다시 연다.
   */
  const cycle = Math.floor(t / FW_SHOW_LEN)
  if (cycle !== fwCycle) {
    fwCycle = cycle
    fwCursor = 0
  }
  const showT = t - cycle * FW_SHOW_LEN
  while (fwCursor < FW_SCORE.length && FW_SCORE[fwCursor].t <= showT) {
    fwLaunch(FW_SCORE[fwCursor])
    fwCursor++
  }

  // ── 올라가는 것 ──
  const shellSegs = []
  const nextShells = []
  for (const sh of fwShells) {
    sh.age += dt
    sh.vy += FW_GRAV * dt
    sh.x += sh.vx * dt
    sh.y += sh.vy * dt
    if (sh.age >= sh.fuse) {
      fwBurst(sh)
      continue
    }
    nextShells.push(sh)
    // 올라가는 자국. 꼬리는 지나온 쪽으로 뻗는다
    shellSegs.push(
      `M${(sh.x - sh.vx * 0.09).toFixed(1)} ${(sh.y - sh.vy * 0.09).toFixed(1)}L${sh.x.toFixed(1)} ${sh.y.toFixed(1)}`,
    )
  }
  fwShells = nextShells

  // ── 흩어지는 것 ──
  const bins = new Map()
  const nextSparks = []
  for (const sp of fwSparks) {
    sp.age += dt
    if (sp.age > sp.life) continue
    // 항력이 먼저 붙잡고, 남은 것을 중력이 끌어내린다
    const k = Math.exp(-sp.drag * dt)
    sp.vx *= k
    sp.vy = sp.vy * k + FW_GRAV * dt
    sp.x += sp.vx * dt
    sp.y += sp.vy * dt
    nextSparks.push(sp)

    const u = sp.age / sp.life
    const flick = 0.72 + 0.28 * Math.sin(sp.age * sp.tw + sp.twp)
    const o = Math.min(1, (1 - u) * 1.5) * flick
    if (o < 0.06) continue
    /*
     * 꼬리 길이.
     *
     * 짧게 뒀더니 사그라질 무렵엔 알갱이가 점이 됐다. 불티는 점이 아니라
     * 획이다 — 눈에 잔상이 남아서 그렇게 보인다. 지나온 자리를 조금 길게
     * 잡아 주면 빠른 것은 길게 늘어나고 느려진 것은 짧아진다.
     */
    const tail = 0.14
    const key = `${sp.pal[sp.ci]}|${Math.min(FW_BUCKETS - 1, Math.floor(o * FW_BUCKETS))}|${sp.fat ? 1 : 0}`
    const seg = `M${(sp.x - sp.vx * tail).toFixed(1)} ${(sp.y - sp.vy * tail).toFixed(1)}L${sp.x.toFixed(1)} ${sp.y.toFixed(1)}`
    if (!bins.has(key)) bins.set(key, [])
    bins.get(key).push(seg)
  }
  fwSparks = nextSparks

  const sky = []
  const mirror = []
  for (const [key, segs] of bins) {
    const [c, b, fat] = key.split('|')
    const o = (Number(b) + 0.7) / FW_BUCKETS
    // 밝은 것일수록 굵다. 사그라지면 가늘어지며 사라진다
    sky.push({ k: key, d: segs.join(''), c, o, w: (fat === '1' ? 2.6 : 1.25) + o * 1.15 })
  }
  if (shellSegs.length)
    sky.push({ k: 'shell', d: shellSegs.join(''), c: '#FFE9B0', o: 0.9, w: 1.8 })

  /*
   * 물에 비친 것.
   *
   * 같은 알갱이를 수면 기준으로 뒤집어 한 번 더 그린다. 세로로 눌러서
   * 그리는데, 비스듬히 내려다보는 수면은 위아래로 짧아 보이기 때문이다.
   * 옅게, 그리고 좌우로 조금 흔들어 둔다 — 물에 비친 것은 늘 흔들린다.
   */
  if (mirrorOn) {
    const wob = Math.sin(t * 1.7) * 1.6
    for (const seg of sky) {
      mirror.push({ k: `m${seg.k}`, d: seg.d, c: seg.c, o: seg.o * 0.45, w: seg.w * 1.6, wob })
    }
  }

  fwFlash = Math.max(0, fwFlash - dt * 2.6)
  // 번쩍임은 이 판에 없다. 가까이 보는 판에서 생긴 것이라 빈 자리로 내준다
  return { sky, mirror, blast: NONE, blastM: NONE, flash: fwFlash * 0.15, flashC: '' }
}

